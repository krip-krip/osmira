"""Generate ptzview.conf from the station configuration.

ptzview has a fixed number of inputs (slots). Cameras fill them in position
order; free slots get a local address that refuses connections at once, so
ptzview just shows NO SIGNAL there. To be removed when ptzview accepts any
number of cameras.
"""

from osmiracam_agent.settings import PtzviewSettings
from osmiracam_agent.station_config import Camera, StationConfig

UNUSED_SLOT_URL = "srt://127.0.0.1:9?mode=caller&streamid=unused"
DEFAULT_LATENCY_MS = 20


def slot_cameras(config: StationConfig, slots: int) -> list[Camera | None]:
    """Camera in each ptzview input (index 0 = cam1), None for a free slot."""
    cameras: list[Camera | None] = list(config.cameras[:slots])
    return cameras + [None] * (slots - len(cameras))


def render(config: StationConfig, settings: PtzviewSettings) -> str:
    cameras = slot_cameras(config, settings.slots)
    used = [c for c in cameras if c is not None]
    # ptzview has one SRT latency for all inputs: take the largest requested.
    latency = max((c.latency_ms for c in used), default=DEFAULT_LATENCY_MS)

    lines = [
        "# Generated by osmiracam-agent from the OsmiraCore configuration.",
        f"# Config version: {config.version}",
        "# Do not edit: overwritten at every configuration change.",
        "",
        "[general]",
        f"srt_latency_ms = {latency}",
        f"http_port = {settings.http_port}",
        f"start_camera = {_start_slot(cameras)}",
    ]
    lines += [f"{key} = {_one_line(value)}" for key, value in sorted(settings.general.items())]

    for index, camera in enumerate(cameras, start=1):
        lines += ["", f"[cam{index}]"]
        if camera is None:
            lines += [f"url = {UNUSED_SLOT_URL}", "label = ", "tally = off"]
        else:
            lines += [f"url = {_one_line(camera.srt_url)}", f"label = {_one_line(camera.label)}"]
            lines += ["tally = off"]
    return "\n".join(lines) + "\n"


def _start_slot(cameras: list[Camera | None]) -> int:
    """First camera the operator may view, else the first input."""
    for index, camera in enumerate(cameras, start=1):
        if camera is not None and camera.view:
            return index
    return 1


def _one_line(value: str) -> str:
    # ptzview.conf is line based: a newline in a label would break the file.
    return " ".join(value.splitlines()).strip()
